// Compiles contracts/*.sol (resolving hegota-support and OpenZeppelin) and writes the committed
// src/contracts/artifacts.ts. Run: bun run build:contracts
import { readFileSync, writeFileSync } from "node:fs";
import { compileFrameContract } from "./compile";

const contracts = [
  ["FrameAccount", "frameAccount"],
  ["FrameSponsor", "frameSponsor"],
  ["FrameAccountFactory", "frameAccountFactory"],
] as const;

let out = "// Generated by scripts/build-contracts.ts. Do not edit.\n\n";
for (const [name, key] of contracts) {
  const source = readFileSync(
    new URL(`../contracts/${name}.sol`, import.meta.url),
    "utf8",
  );
  const { abi, bytecode } = compileFrameContract(name, source);
  out += `export const ${key}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
  out += `export const ${key}Bytecode = ${JSON.stringify(bytecode)} as const;\n\n`;
}
const path = new URL("../src/contracts/artifacts.ts", import.meta.url);
writeFileSync(path, `${out.trimEnd()}\n`);
console.log(`wrote ${path.pathname}`);
